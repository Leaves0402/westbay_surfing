-- ---------------------------------------------------------------------------
-- Aggregate attendance queries (avoid downloading all historical rows).
-- ---------------------------------------------------------------------------

create or replace function public.get_lesson_attendance_overview()
returns table (
  user_id uuid,
  attendance_count bigint,
  teaching_count bigint,
  started_lesson_count bigint
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_current_profile_staff() then
    raise exception '只有幹部與管理員可以查看出席統計。';
  end if;

  return query
  with started_lessons as (
    select lesson.id
    from public.lessons lesson
    where public.lesson_start_timestamp(lesson.lesson_date, lesson.start_time)
      <= (timezone('Asia/Taipei', now()))::timestamp
  ),
  attendance_events as (
    select attendance.user_id, attendance.lesson_id
    from public.lesson_member_attendance attendance
    join started_lessons lesson on lesson.id = attendance.lesson_id
    where attendance.checked_in = true

    union

    select attendance.instructor_id as user_id, attendance.lesson_id
    from public.lesson_instructor_attendance attendance
    join started_lessons lesson on lesson.id = attendance.lesson_id
    where attendance.checked_in = true
  ),
  attendance_counts as (
    select event.user_id, count(*)::bigint as attendance_count
    from attendance_events event
    group by event.user_id
  ),
  teaching_counts as (
    select attendance.instructor_id as user_id, count(distinct attendance.lesson_id)::bigint as teaching_count
    from public.lesson_instructor_attendance attendance
    join started_lessons lesson on lesson.id = attendance.lesson_id
    where attendance.checked_in = true
    group by attendance.instructor_id
  ),
  lesson_total as (
    select count(*)::bigint as started_lesson_count from started_lessons
  )
  select
    profile.id,
    coalesce(attendance_counts.attendance_count, 0),
    coalesce(teaching_counts.teaching_count, 0),
    lesson_total.started_lesson_count
  from public.profiles profile
  cross join lesson_total
  left join attendance_counts on attendance_counts.user_id = profile.id
  left join teaching_counts on teaching_counts.user_id = profile.id
  where profile.role in ('member', 'board_manager', 'officer', 'admin');
end;
$$;

create or replace function public.get_my_lesson_attendance_summary()
returns table (
  attended_count bigint,
  started_lesson_count bigint
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or not public.is_current_profile_member() then
    raise exception '只有正式社員可以查看出席統計。';
  end if;

  return query
  with started_lessons as (
    select lesson.id
    from public.lessons lesson
    where public.lesson_start_timestamp(lesson.lesson_date, lesson.start_time)
      <= (timezone('Asia/Taipei', now()))::timestamp
  ),
  my_attendance as (
    select attendance.lesson_id
    from public.lesson_member_attendance attendance
    join started_lessons lesson on lesson.id = attendance.lesson_id
    where attendance.user_id = auth.uid()
      and attendance.checked_in = true

    union

    select attendance.lesson_id
    from public.lesson_instructor_attendance attendance
    join started_lessons lesson on lesson.id = attendance.lesson_id
    where attendance.instructor_id = auth.uid()
      and attendance.checked_in = true
  )
  select
    (select count(*)::bigint from my_attendance),
    (select count(*)::bigint from started_lessons);
end;
$$;

create or replace function public.get_public_rental_schedule_range(
  target_start_date date,
  target_end_date date
)
returns table (
  id uuid,
  rental_date date,
  start_time time,
  end_time time,
  capacity integer,
  min_surf_level text,
  is_open boolean,
  registration_count integer,
  remaining_capacity integer
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if target_start_date is null
    or target_end_date is null
    or target_end_date < target_start_date
  then
    raise exception '租板日期範圍無效。';
  end if;

  if target_end_date - target_start_date > 62 then
    raise exception '公開租板日曆一次最多查詢 63 天。';
  end if;

  return query
  select
    slot.id,
    slot.rental_date,
    slot.start_time,
    slot.end_time,
    slot.capacity,
    slot.min_surf_level,
    slot.is_open,
    count(registration.id)::integer,
    greatest(slot.capacity - count(registration.id), 0)::integer
  from public.rental_slots slot
  left join public.rental_registrations registration
    on registration.rental_slot_id = slot.id
  where slot.rental_date between target_start_date and target_end_date
  group by
    slot.id,
    slot.rental_date,
    slot.start_time,
    slot.end_time,
    slot.capacity,
    slot.min_surf_level,
    slot.is_open
  order by slot.rental_date asc, slot.start_time asc;
end;
$$;

