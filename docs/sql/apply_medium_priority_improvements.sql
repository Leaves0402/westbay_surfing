create or replace function public.enforce_admin_governance()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  governance_row public.club_governance%rowtype;
  actor_role text;
  current_additional_admin_count integer;
begin
  select *
  into governance_row
  from public.club_governance
  where singleton = true
  for update;

  if governance_row.owner_user_id is null then
    raise exception '尚未設定站主帳號。';
  end if;

  if tg_op = 'DELETE' then
    if old.id = governance_row.owner_user_id then
      raise exception '站主帳號永遠不能被移除。';
    end if;

    if auth.uid() is not null then
      select profile.role::text
      into actor_role
      from public.profiles profile
      where profile.id = auth.uid();

      if old.id = auth.uid() then
        raise exception '不能移除自己的社員資料。';
      end if;

      if coalesce(actor_role, 'pending') not in ('officer', 'admin') then
        raise exception '只有幹部與管理員可以移除社員。';
      end if;

      if old.role = 'admin' and actor_role <> 'admin' then
        raise exception '只有管理員可以移除管理員。';
      end if;
    end if;

    return old;
  end if;

  if old.role is not distinct from new.role then
    return new;
  end if;

  if auth.uid() is not null and old.id = auth.uid() then
    raise exception '不能調整自己的身分。';
  end if;

  if new.id = governance_row.owner_user_id and new.role <> 'admin' then
    raise exception '站主帳號永遠必須保留管理員身分。';
  end if;

  if auth.uid() is not null then
    select profile.role::text
    into actor_role
    from public.profiles profile
    where profile.id = auth.uid();

    if coalesce(actor_role, 'pending') not in ('officer', 'admin') then
      raise exception '只有幹部與管理員可以調整社員身分。';
    end if;

    if (old.role = 'admin' or new.role = 'admin') and actor_role <> 'admin' then
      raise exception '只有管理員可以授予或移除管理員身分。';
    end if;
  end if;

  if old.role <> 'admin'
    and new.role = 'admin'
    and new.id <> governance_row.owner_user_id
  then
    select count(*)::integer
    into current_additional_admin_count
    from public.profiles profile
    where profile.role = 'admin'
      and profile.id <> governance_row.owner_user_id;

    if current_additional_admin_count >= governance_row.additional_admin_limit then
      raise exception '管理員名額已滿；站主之外最多只能有 % 位管理員。',
        governance_row.additional_admin_limit;
    end if;
  end if;

  return new;
end;
$$;

