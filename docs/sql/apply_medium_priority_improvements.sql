create or replace function public.update_member_role(
  target_user_id uuid,
  target_role text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_role text := coalesce(public.current_profile_role(), 'pending');
  governance_row public.club_governance%rowtype;
  current_target_role text;
begin
  if auth.uid() is null then
    raise exception '請先登入。';
  end if;

  if actor_role not in ('officer', 'admin') then
    raise exception '只有幹部與管理員可以調整社員身分。';
  end if;

  if target_user_id = auth.uid() then
    raise exception '不能調整自己的身分。';
  end if;

  if target_role not in ('member', 'board_manager', 'officer', 'admin') then
    raise exception '社員身分無效。';
  end if;

  select *
  into governance_row
  from public.club_governance
  where singleton = true
  for update;

  if target_user_id = governance_row.owner_user_id then
    raise exception '站主帳號永遠不能被調整或移除。';
  end if;

  select profile.role::text
  into current_target_role
  from public.profiles profile
  where profile.id = target_user_id
  for update;

  if current_target_role is null then
    raise exception '找不到社員。';
  end if;

  if actor_role = 'officer'
    and (current_target_role = 'admin' or target_role = 'admin')
  then
    raise exception '只有管理員可以授予或移除管理員身分。';
  end if;

  perform set_config('app.member_role_change_source', 'member_role_rpc', true);

  update public.profiles
  set role = target_role, updated_at = now()
  where id = target_user_id;
end;
$$;

