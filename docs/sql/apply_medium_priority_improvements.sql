create or replace function public.promote_lesson_waitlist_member(
  target_lesson_id uuid,
  target_user_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  lesson_row public.lessons%rowtype;
  confirmed_count integer;
  first_waitlist_user_id uuid;
begin
  if not public.is_current_profile_staff() then
    raise exception '只有幹部與管理員可以正式遞補候補社員。';
  end if;

  select *
  into lesson_row
  from public.lessons
  where id = target_lesson_id
  for update;

  if lesson_row.id is null then
    raise exception '找不到社課。';
  end if;

  select count(*)::integer
  into confirmed_count
  from public.lesson_participants participant
  where participant.lesson_id = target_lesson_id
    and participant.status = 'confirmed';

  if confirmed_count >= lesson_row.capacity then
    raise exception '正取名額已滿，必須先釋出名額才能遞補。';
  end if;

  select participant.user_id
  into first_waitlist_user_id
  from public.lesson_participants participant
  where participant.lesson_id = target_lesson_id
    and participant.status = 'waitlist'
  order by participant.waitlist_order asc, participant.created_at asc
  limit 1
  for update;

  if first_waitlist_user_id is null then
    raise exception '目前沒有候補社員。';
  end if;

  if first_waitlist_user_id <> target_user_id then
    raise exception '必須依候補順序遞補。';
  end if;

  update public.lesson_participants
  set
    status = 'confirmed',
    waitlist_order = null,
    updated_at = now()
  where lesson_id = target_lesson_id
    and user_id = target_user_id
    and status = 'waitlist';

  with ordered as (
    select
      participant.id,
      row_number() over (
        order by participant.waitlist_order asc nulls last,
          participant.created_at asc,
          participant.id asc
      )::integer as new_order
    from public.lesson_participants participant
    where participant.lesson_id = target_lesson_id
      and participant.status = 'waitlist'
  )
  update public.lesson_participants participant
  set waitlist_order = -ordered.new_order
  from ordered
  where participant.id = ordered.id;

  update public.lesson_participants participant
  set waitlist_order = -participant.waitlist_order
  where participant.lesson_id = target_lesson_id
    and participant.status = 'waitlist'
    and participant.waitlist_order < 0;
end;
$$;

