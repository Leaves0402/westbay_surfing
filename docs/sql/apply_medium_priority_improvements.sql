create or replace function public.approve_surf_level_request(target_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target_level text;
  target_role text;
  governance_row public.club_governance%rowtype;
begin
  if coalesce(public.current_profile_role(), 'pending') <> 'admin' then
    raise exception '只有管理員可以核准衝浪程度。';
  end if;

  select *
  into governance_row
  from public.club_governance
  where singleton = true
  for update;

  select profile.requested_surf_level, profile.role::text
  into target_level, target_role
  from public.profiles profile
  where profile.id = target_user_id
  for update;

  if target_level is null then
    raise exception '目前沒有待審核的程度申請。';
  end if;

  if target_role not in ('member', 'board_manager', 'officer', 'admin') then
    raise exception '請先將申請人審核為正式社員，再處理程度申請。';
  end if;

  if target_level = '進階' then
    perform set_config(
      'app.member_role_change_source',
      'advanced_surf_level_approval',
      true
    );

    update public.profiles
    set
      surf_level = target_level,
      role = 'admin',
      requested_surf_level = null,
      requested_surf_level_at = null,
      updated_at = now()
    where id = target_user_id;
  else
    update public.profiles
    set
      surf_level = target_level,
      requested_surf_level = null,
      requested_surf_level_at = null,
      updated_at = now()
    where id = target_user_id;
  end if;
end;
$$;

